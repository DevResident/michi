package michi.versioning

import org.gradle.api.DefaultTask
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputFile
import org.gradle.api.tasks.TaskAction

abstract class WriteIosVersionConfigTask : DefaultTask() {

    @get:Input
    abstract val marketingVersion: Property<String>

    @get:Input
    abstract val versionCode: Property<Int>

    @get:Input
    abstract val fullVersionName: Property<String>

    @get:OutputFile
    abstract val outputFile: RegularFileProperty

    @TaskAction
    fun write() {
        val file = outputFile.get().asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            // Generated by :writeIosVersionConfig from the latest vX.Y.Z git tag.
            // Do not edit. This file is not tracked by git.
            // Full version: ${fullVersionName.get()}
            MARKETING_VERSION=${marketingVersion.get()}
            CURRENT_PROJECT_VERSION=${versionCode.get()}
            """.trimIndent() + "\n",
        )
    }
}
